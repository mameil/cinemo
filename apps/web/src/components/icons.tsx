import type { ReactNode, SVGProps } from "react";

interface IconProps extends SVGProps<SVGSVGElement> {
  /** 픽셀 크기 (기본 14) */
  size?: number;
}

/**
 * 공용 스트로크 아이콘 (Feather 기반, currentColor).
 * 플랫폼 이모지 대신 사용 — 팔레트와 톤이 맞고 OS 간 렌더링이 일정하다.
 */
function createIcon(displayName: string, children: ReactNode) {
  function Icon({ size = 14, className = "", ...rest }: IconProps) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        className={`inline-block flex-none align-[-0.125em] ${className}`}
        {...rest}
      >
        {children}
      </svg>
    );
  }
  Icon.displayName = displayName;
  return Icon;
}

